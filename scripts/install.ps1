<#
.SYNOPSIS
  HALOFLUX Universal Agent Visualizer — one-command install for Windows.

.DESCRIPTION
  Idempotent. What it does, in order:
    1. verifies Node >= 22 and the repo layout;
    2. installs dev dependencies and builds the TypeScript event schema;
    3. snapshots every host config file it might touch into config/backups/<utc>/;
    4. installs the host adapters (delegates to scripts/install-adapters.ps1 when present);
    5. creates a Start Menu shortcut and start/stop helper scripts;
    6. optionally starts the bridge + desktop companion.

  Nothing is written into another application's directory. Host config edits are
  performed by the adapters and are reversible via uninstall-adapters.ps1 or
  scripts/haloflux.mjs restore <timestamp>.

.PARAMETER Mode
  Companion window mode: window (default), overlay, compact.

.PARAMETER SkipAdapters
  Do not touch any host configuration.

.PARAMETER NoShortcut
  Do not create a Start Menu shortcut.

.PARAMETER Start
  Start bridge + companion after installing.

.EXAMPLE
  pwsh -File scripts\install.ps1 -Start
#>
[CmdletBinding()]
param(
  [ValidateSet('window', 'overlay', 'compact')]
  [string]$Mode = 'window',
  [switch]$SkipAdapters,
  [switch]$NoShortcut,
  [switch]$Start
)

$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

function Write-Step([string]$Text) { Write-Host "`n== $Text ==" -ForegroundColor Cyan }
function Write-Ok([string]$Text) { Write-Host "  OK   $Text" -ForegroundColor Green }
function Write-Warn([string]$Text) { Write-Host "  WARN $Text" -ForegroundColor Yellow }

Write-Host "HALOFLUX Universal Agent Visualizer - installer" -ForegroundColor Magenta
Write-Host "root: $Root"

Write-Step '1/6 toolchain'
$node = Get-Command node -ErrorAction SilentlyContinue
if (-not $node) { throw 'Node.js not found. Install Node >= 22 first.' }
$nodeVersion = (& node --version).TrimStart('v')
if ([version]$nodeVersion -lt [version]'22.0.0') { throw "Node $nodeVersion is too old (need >= 22)." }
Write-Ok "node $nodeVersion"
$electronCandidates = @(@(
  $env:HALOFLUX_ELECTRON,
  (Join-Path $Root 'node_modules\electron\dist\electron.exe'),
  (Join-Path $env:USERPROFILE '.dsh\electron\electron.exe')
) | Where-Object { $_ -and (Test-Path $_) })
if ($electronCandidates.Count -eq 0) { Write-Warn 'Electron not found; companion will not launch. Set HALOFLUX_ELECTRON.' }
else { Write-Ok "electron $($electronCandidates[0])" }

Write-Step '2/6 build'
if (Test-Path 'package-lock.json') { & npm install --no-audit --no-fund | Out-Host }
& npm run build | Out-Host
if ($LASTEXITCODE -ne 0) { throw 'build failed' }
Write-Ok 'event schema built'

Write-Step '3/6 config snapshot'
& node scripts/haloflux.mjs backup --label install | Out-Host
if ($LASTEXITCODE -ne 0) { Write-Warn 'backup step reported a problem (continuing)' }

Write-Step '4/6 host adapters'
if ($SkipAdapters) {
  Write-Warn 'skipped by -SkipAdapters'
} elseif (Test-Path 'scripts\install-adapters.ps1') {
  & powershell -NoProfile -ExecutionPolicy Bypass -File 'scripts\install-adapters.ps1' | Out-Host
  if ($LASTEXITCODE -ne 0) { Write-Warn 'adapter installer reported a problem; see docs/05-install-uninstall.md' }
} else {
  # Fallback: the per-host installers are always shipped; the aggregate script is
  # only a convenience wrapper. Default to the two hosts whose hooks are proven
  # on this machine; other hosts stay opt-in (see docs/05-install-uninstall.md).
  Write-Warn 'scripts\install-adapters.ps1 missing - using per-host installers (claude-code, codex)'
  foreach ($hostId in @('claude-code', 'codex')) {
    $installer = Join-Path $Root "adapters\$hostId\install.ps1"
    if (Test-Path $installer) {
      Write-Host "  installing $hostId ..." -ForegroundColor DarkGray
      & powershell -NoProfile -ExecutionPolicy Bypass -File $installer -Json | Out-Host
      if ($LASTEXITCODE -ne 0) { Write-Warn "$hostId installer returned $LASTEXITCODE" }
    } else {
      Write-Warn "missing $installer"
    }
  }
}

Write-Step '5/6 launchers'
$binDir = Join-Path $Root 'bin'
New-Item -ItemType Directory -Force $binDir | Out-Null
$startCmd = Join-Path $binDir 'HALOFLUX.cmd'
@"
@echo off
rem HALOFLUX launcher (generated by scripts/install.ps1)
cd /d "$Root"
node scripts\haloflux.mjs start --mode $Mode
"@ | Set-Content -Path $startCmd -Encoding ASCII
$stopCmd = Join-Path $binDir 'HALOFLUX-stop.cmd'
@"
@echo off
cd /d "$Root"
node scripts\haloflux.mjs stop
"@ | Set-Content -Path $stopCmd -Encoding ASCII
Write-Ok "launchers: $startCmd"

$shortcutPath = ''
if (-not $NoShortcut) {
  try {
    $startMenu = [Environment]::GetFolderPath('Programs')
    $shortcutPath = Join-Path $startMenu 'HALOFLUX Universal Agent Visualizer.lnk'
    $shell = New-Object -ComObject WScript.Shell
    $shortcut = $shell.CreateShortcut($shortcutPath)
    $shortcut.TargetPath = $startCmd
    $shortcut.WorkingDirectory = $Root
    $shortcut.Description = 'HALOFLUX universal agent visualizer'
    $shortcut.Save()
    Write-Ok "Start Menu shortcut: $shortcutPath"
  } catch {
    Write-Warn "shortcut not created: $($_.Exception.Message)"
    $shortcutPath = ''
  }
}

$manifest = [ordered]@{
  installedAt = (Get-Date).ToUniversalTime().ToString('o')
  root = $Root
  mode = $Mode
  shortcut = $shortcutPath
  adapters = (-not $SkipAdapters)
  node = $nodeVersion
  electron = ($electronCandidates | Select-Object -First 1)
}
New-Item -ItemType Directory -Force (Join-Path $Root 'config') | Out-Null
$manifest | ConvertTo-Json -Depth 4 | Set-Content -Path (Join-Path $Root 'config\install-manifest.json') -Encoding UTF8
Write-Ok 'manifest: config\install-manifest.json'

Write-Step '6/6 done'
Write-Host "  start:   $startCmd" -ForegroundColor Green
Write-Host "  status:  node scripts\haloflux.mjs status" -ForegroundColor Green
Write-Host "  doctor:  node scripts\haloflux.mjs doctor" -ForegroundColor Green
Write-Host "  stop:    $stopCmd" -ForegroundColor Green
Write-Host "  remove:  pwsh -File scripts\uninstall.ps1" -ForegroundColor Green
Write-Host "  license: PolyForm Noncommercial 1.0.0 (see LICENSE / NOTICE)" -ForegroundColor DarkGray

if ($Start) {
  Write-Step 'starting bridge + companion'
  & node scripts/haloflux.mjs start --mode $Mode | Out-Host
}
